#!/usr/bin/env python3
"""Re-draws the Debt Angel app icon (scripts/generate_icons.py in the app repo) as SVG.
Run:  python3 scripts/gen-logo.py   -> writes app/icon.svg and components/logo-data.ts"""
import math, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = 1024; c = S/2; scale = 0.95
unit = S*0.40*scale
pivot_y = c + S*0.10*scale
gap = S*0.035*scale
feathers = [(-62,.78,.20),(-46,.92,.21),(-30,1.02,.22),(-14,1.04,.22),(2,.98,.21),(18,.86,.20),(34,.70,.18)]
ell = []
for direction, px in ((-1, c-gap), (1, c+gap)):
    for ang, ln, wd in feathers:
        a = ang if direction > 0 else 180-ang
        L = ln*unit
        cx = px + math.cos(math.radians(a))*L/2
        cy = pivot_y + math.sin(math.radians(a))*L/2
        ell.append(dict(cx=round(cx,1), cy=round(cy,1), rx=round(L/2,1), ry=round(wd*unit/2,1), rot=round(a,1)))
bw, bh = S*0.13*scale, S*0.20*scale
body = dict(cx=round(c,1), cy=round(pivot_y+(bh*0.55-bh*0.45)/2,1), rx=round(bw/2,1), ry=round(bh/2,1))
halo = dict(cx=round(c,1), cy=round(pivot_y-S*0.215*scale,1), rx=round(S*0.12*scale,1), ry=round(S*0.04*scale,1), sw=round(S*0.028*scale,1))
data = dict(wings=ell, body=body, halo=halo)
with open(os.path.join(ROOT,'components','logo-data.ts'),'w') as f:
    f.write('// Generated by scripts/gen-logo.py: the app icon artwork, as SVG ellipse data (1024 x 1024 viewBox).\nexport const LOGO = '+json.dumps(data,indent=1)+' as const;\n')
def mark():
    out=[]
    for e in ell:
        out.append(f'<ellipse cx="{e["cx"]}" cy="{e["cy"]}" rx="{e["rx"]}" ry="{e["ry"]}" transform="rotate({e["rot"]} {e["cx"]} {e["cy"]})" fill="#fff" stroke="#C4C0FA" stroke-width="4"/>')
    out.append(f'<ellipse cx="{body["cx"]}" cy="{body["cy"]}" rx="{body["rx"]}" ry="{body["ry"]}" fill="#fff" stroke="#C4C0FA" stroke-width="4"/>')
    out.append(f'<ellipse cx="{halo["cx"]}" cy="{halo["cy"]}" rx="{halo["rx"]}" ry="{halo["ry"]}" fill="none" stroke="#FFC933" stroke-width="{halo["sw"]}"/>')
    return ''.join(out)
svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><defs><linearGradient id="g" x1="0" y1="0" x2="0.5" y2="1"><stop offset="0" stop-color="#7C70FF"/><stop offset="1" stop-color="#4F46E5"/></linearGradient></defs><rect width="1024" height="1024" rx="230" fill="url(#g)"/>{mark()}</svg>'
open(os.path.join(ROOT,'app','icon.svg'),'w').write(svg)
print('ok')
